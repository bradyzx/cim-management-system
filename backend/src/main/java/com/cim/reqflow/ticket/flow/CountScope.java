package com.cim.reqflow.ticket.flow;

/**
 * 退回计次维度。
 * <p>
 * 「同一退回点第 3 次升级」听起来简单，难点在「按什么数」：
 * 同一张单可能被一个人退三次，也可能被三个人各退一次，两种数法结论完全不同。
 * 本枚举把这四种维度定死，计数一律查 req_flow_log 聚合，
 * 不用 req_ticket.return_count —— 它只有一个总数，分不清是哪个点退的。
 *
 * @author Haijie Xiao
 * @date 2026-11-04
 */
public enum CountScope {

    /** 不计数。① 文档重生成（本人反复改不该被惩罚）、⑨ 评价不符合（已闭环只打标） */
    NONE,

    /** 按单计数：同一张单在该退回点上的记录数 */
    TICKET,

    /** 按人计数：同一张单 + 同一操作人在该退回点上的记录数。③ 拒接单人 2 次 */
    PERSON,

    /** 按组计数：同一张单在一组退回点上的记录数合计。⑫⑬⑭ 三步合计 3 次 */
    GROUP
}
